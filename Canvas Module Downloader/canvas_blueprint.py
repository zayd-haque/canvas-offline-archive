    def synthesize_missing_modules(self):
        """Ensures all course materials on disk are accessible via modules.
        If a course has no modules (e.g. PSYCH 100B), synthesizes modules from physical folders.
        If a course has modules but orphaned files exist (e.g. CHEM 14D Discussion Slides or Reaction Maps),
        adds dedicated modules for them.
        """
        # 1. Clean up placeholder / syntax error modules
        self.modules = [
            m for m in self.modules 
            if m.get("id") != "{{ id }}" and not (m.get("title") == "General Materials" and len(m.get("items", [])) == 0)
        ]

        # Case A: Modules array is completely empty -> Synthesize from folder categories
        if len(self.modules) == 0 and self.file_path_map:
            folders_dict = {}
            for fname, rpath in sorted(self.file_path_map.items()):
                if is_synthetic_file(fname, rpath):
                    continue
                # Determine folder category
                parts = rpath.split("/")
                category = "Course Materials"
                if len(parts) > 1:
                    # e.g., "PSYCH 100B Lectures & Resources/PSYCH 100B Lecture Slides/..."
                    # Extract the meaningful category name
                    cat_candidate = parts[1] if len(parts) > 2 else parts[0]
                    category = clean_module_title(cat_candidate, self.course_name)
                folders_dict.setdefault(category, []).append({
                    "type": "generic",
                    "title": fname,
                    "local_file": rpath,
                    "indent": 0
                })

            # Sort items within each category using natural alphanumeric order
            for items in folders_dict.values():
                items.sort(key=lambda it: natural_sort_key(it.get("title", "")))

            # Sort categories by hierarchical tier and natural chronological order
            sorted_categories = sorted(
                folders_dict.items(),
                key=lambda pair: module_category_sort_key(pair[0])
            )

            for cat_idx, (cat_name, items) in enumerate(sorted_categories, start=1):
                self.modules.append({
                    "id": f"synth_{cat_idx}",
                    "title": cat_name,
                    "items": items
                })
            return

        # Case B: Modules exist, group any unlinked files on disk by their subfolder/category
        linked_files = set()
        for mod in self.modules:
            for item in mod.get("items", []):
                lf = item.get("local_file")
                if lf:
                    linked_files.add(lf)
                    linked_files.add(os.path.basename(lf))

        # Check for unlinked files clustering by common multi-word topic prefix (e.g. "Reaction Map")
        clustered_files = set()
        common_prefixes = {}
        for fname, rpath in sorted(self.file_path_map.items()):
            if is_synthetic_file(fname, rpath) or fname in linked_files or rpath in linked_files:
                continue
            words = re.findall(r'[A-Za-z0-9]+', fname)
            if len(words) >= 2 and words[0].lower() not in {"chapter", "ch", "week", "lecture", "assignment", "homework"}:
                prefix = f"{words[0]} {words[1]}"
                common_prefixes.setdefault(prefix.lower(), []).append((prefix, fname, rpath))

        for p_low, p_items in common_prefixes.items():
            if len(p_items) >= 2:
                disp_prefix = p_items[0][0]
                cluster_title = f"{disp_prefix}s & Guides" if not disp_prefix.endswith("s") else f"{disp_prefix} & Guides"
                cluster_mod_items = []
                for _, fn, rp in p_items:
                    cluster_mod_items.append({
                        "type": "generic",
                        "title": fn,
                        "local_file": rp,
                        "indent": 0
                    })
                    clustered_files.add(fn)
                    clustered_files.add(rp)
                self.modules.append({
                    "id": f"mod_cluster_{re.sub(r'[^a-zA-Z0-9_]', '_', p_low)}_{len(self.modules)+1}",
                    "title": cluster_title,
                    "items": cluster_mod_items
                })

        unlinked_by_folder = {}
        for fname, rpath in sorted(self.file_path_map.items()):
            if is_synthetic_file(fname, rpath) or fname in clustered_files or rpath in clustered_files:
                continue
            if fname not in linked_files and rpath not in linked_files:
                parts = rpath.split("/")
                if len(parts) > 1:
                    cat_candidate = parts[1] if len(parts) > 2 else parts[0]
                    category = clean_module_title(cat_candidate, self.course_name)
                else:
                    category = "Additional Materials"

                if "discussion slides" in category.lower() or "discussion presentation" in category.lower():
                    category = "Discussion Presentations & Slides"

                unlinked_by_folder.setdefault(category, []).append({
                    "type": "generic",
                    "title": fname,
                    "local_file": rpath,
                    "indent": 0
                })

        for cat_name, items in unlinked_by_folder.items():
            cat_lower = cat_name.lower()
            existing = next((m for m in self.modules if cat_lower in m.get("title", "").lower() or m.get("title", "").lower() in cat_lower), None)
            if existing:
                existing_files = {it.get("local_file") for it in existing.get("items", [])}
                for it in items:
                    if it["local_file"] not in existing_files:
                        existing.setdefault("items", []).append(it)
            else:
                self.modules.append({
                    "id": f"mod_synth_{re.sub(r'[^a-zA-Z0-9_]', '_', cat_name.lower())}_{len(self.modules)+1}",
                    "title": cat_name,
                    "items": items
                })

    def link_module_items_to_files(self):
        """Cross-references module items with the organized file paths on disk, resolving synonyms and key files accurately."""
        # 1. Prune placeholder / syntax error modules
        self.modules = [
            m for m in self.modules 
            if m.get("id") != "{{ id }}" and not (m.get("title") == "General Materials" and len(m.get("items", [])) == 0)
        ]

        normalized_map = {}
        for fname, rpath in self.file_path_map.items():
            base, _ = os.path.splitext(fname)
            clean_fname = re.sub(r'\s+', ' ', fname).strip().lower()
            clean_base = re.sub(r'\s+', ' ', base).strip().lower()
            normalized_map[clean_fname] = rpath
            normalized_map[clean_base] = rpath

        def is_key_file(s: str) -> bool:
            low = s.lower()
            return any(k in low for k in ["key", "solution", "soln", "answer key"])

        for mod in self.modules:
            for item in mod.get("items", []):
                title = item.get("title", "")
                title_clean = re.sub(r'\s+', ' ', title).strip().lower()
                base_clean = re.sub(r'\s+', ' ', os.path.splitext(title)[0]).strip().lower()

                # 1. Exact or normalized match
                if title_clean in normalized_map:
                    item["local_file"] = normalized_map[title_clean]
                    continue
                if base_clean in normalized_map:
                    item["local_file"] = normalized_map[base_clean]
                    continue

                # 2. Token overlap & substring match respecting key vs non-key
                is_key = is_key_file(title_clean)
                item_tokens = set(re.findall(r'[a-z0-9]+', title_clean)) - {
                    'the', 'a', 'an', 'and', 'or', 'for', 'of', 'in', 'on', 'at', 'to', 'with',
                    'pdf', 'pptx', 'docx', 'xlsx', 'txt', 'review', 'problems', 'exercises'
                }

                best_match = None
                best_score = 0

                for fname_clean, rpath in normalized_map.items():
                    target_is_key = is_key_file(fname_clean)
                    if is_key != target_is_key:
                        continue

                    # Substring match
                    if fname_clean in title_clean or title_clean in fname_clean or base_clean in fname_clean or fname_clean in base_clean:
                        best_match = rpath
                        break

                    # Token overlap match
                    fn_tokens = set(re.findall(r'[a-z0-9]+', fname_clean)) - {
                        'the', 'a', 'an', 'and', 'or', 'for', 'of', 'in', 'on', 'at', 'to', 'with',
                        'pdf', 'pptx', 'docx', 'xlsx', 'txt', 'review', 'problems', 'exercises'
                    }
                    if not item_tokens or not fn_tokens:
                        continue

                    overlap = len(item_tokens & fn_tokens)
                    score = overlap / max(len(item_tokens), len(fn_tokens))
                    if overlap >= 2 and score > best_score:
                        best_score = score
                        best_match = rpath

                if best_match:
                    item["local_file"] = best_match

