    def hydrate_from_canvas_api(self, cookies_path: str = None):
        """Enriches assignments and announcements with authoritative dates directly from Canvas REST API endpoints."""
        import requests
        from urllib.parse import urlparse

        if not cookies_path:
            p1 = os.path.join(self.output_dir, ".session_cookies.json")
            parent = os.path.dirname(self.output_dir.rstrip("/\\"))
            p2 = os.path.join(parent, ".session_cookies.json") if parent else ""
            if os.path.exists(p1):
                cookies_path = p1
            elif p2 and os.path.exists(p2):
                cookies_path = p2
            else:
                return

        if not os.path.exists(cookies_path):
            return

        parsed = urlparse(self.course_url)
        course_match = re.search(r'(/courses/\d+)', parsed.path)
        if not course_match:
            return
        course_id = course_match.group(1).replace("/courses/", "")

        try:
            with open(cookies_path, "r", encoding="utf-8") as f:
                cookies = json.load(f)
        except Exception:
            return

        session = requests.Session()
        session.headers.update({"User-Agent": "Mozilla/5.0 (Macintosh; Intel Mac OS X 10_15_7)"})
        for c in cookies:
            session.cookies.set(c["name"], c["value"], domain=c.get("domain", ""), path=c.get("path", "/"))

        def clean_key(s: str) -> str:
            return re.sub(r'[^a-z0-9]', '', str(s).lower())

        api_base = f"{parsed.scheme}://{parsed.netloc}/api/v1/courses/{course_id}"

        # 1. Hydrate Announcements
        try:
            r_ann = session.get(f"{api_base}/discussion_topics?only_announcements=true&per_page=100", timeout=15)
            if r_ann.status_code == 200:
                ann_list = r_ann.json()
                ann_by_key = {clean_key(a.get("title", "")): a for a in ann_list}
                for bp_ann in self.announcements:
                    ck = clean_key(bp_ann.get("title", ""))
                    matched = ann_by_key.get(ck)
                    if not matched:
                        for k, v in ann_by_key.items():
                            if k in ck or ck in k:
                                matched = v
                                break
                    if matched:
                        real_date = matched.get("posted_at") or matched.get("created_at")
                        if real_date:
                            bp_ann["posted_at"] = real_date
                            bp_ann["date"] = real_date[:10]
        except Exception as e:
            print(f"   ℹ️ Notice during announcements API hydration: {e}")

        # 2. Hydrate Assignments
        try:
            r_assign = session.get(f"{api_base}/assignments?per_page=100", timeout=15)
            if r_assign.status_code == 200:
                assign_list = r_assign.json()
                assign_by_key = {clean_key(a.get("name", "")): a for a in assign_list}
                for bp_assign in self.assignments:
                    ck = clean_key(bp_assign.get("title", ""))
                    matched = assign_by_key.get(ck)
                    if not matched:
                        for k, v in assign_by_key.items():
                            if k in ck or ck in k:
                                matched = v
                                break
                    if matched:
                        assigned_date = matched.get("unlock_at") or matched.get("created_at")
                        due_date = matched.get("due_at")
                        lock_date = matched.get("lock_at")
                        pts = matched.get("points_possible")

                        if assigned_date:
                            bp_assign["available_from"] = assigned_date
                            bp_assign["date_assigned"] = assigned_date[:10]
                            bp_assign["created_at"] = matched.get("created_at")
                        if due_date:
                            bp_assign["due_date"] = due_date
                        if lock_date:
                            bp_assign["until"] = lock_date
                        if pts is not None:
                            bp_assign["points"] = pts
        except Exception as e:
            print(f"   ℹ️ Notice during assignments API hydration: {e}")

